import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {Workbook} from '@oai/artifact-tool';
const dir=fileURLToPath(new URL('.',import.meta.url));
const selection=JSON.parse(await fs.readFile(`${dir}/selection.json`,'utf8'));
const rows=selection.DigiKey;
const refs=rows.flatMap(r=>r.References.split(',').map(x=>x.trim()));
if(rows.length!==20||refs.length!==30||new Set(refs).size!==30)throw Error('Coverage');
if(rows.reduce((s,r)=>s+r.Order_Quantity,0)!==115)throw Error('Quantity');
const cap=rows.find(r=>r.MPN==='HVH1020-2R7705-R');
if(cap.Supplier_Part_Number!=='283-HVH1020-2R7705-R-ND'||cap.Order_Quantity!==6)throw Error('Supercapacitor');
const wb=Workbook.create(),sh=wb.worksheets.add('DigiKey');
const matrix=[['DigiKey Part Number','Quantity','Customer Reference'],...rows.map(r=>[r.Supplier_Part_Number,r.Order_Quantity,r.References])];
sh.getRange('A1:C21').values=matrix;
const actual=sh.getRange('A1:C21').values;
if(JSON.stringify(actual)!==JSON.stringify(matrix))throw Error('Worksheet parity');
const csv='\ufeff'+actual.map(r=>r.map(v=>'"'+String(v).replaceAll('"','""')+'"').join(',')).join('\r\n')+'\r\n';
await fs.writeFile(`${dir}/DigiKey_COMPLETE_1set.csv`,csv,'utf8');
console.log(JSON.stringify({lines:rows.length,required_references:refs.length,order_pieces:115,supercapacitor_quantity:6,price_basis:selection.date,subtotal_ex_tax:6014,file:'DigiKey_COMPLETE_1set.csv'}));
